"""The v0.7 ModelFit example reproduces its committed recorded trials and artifacts,
and the committed recommendations meet the milestone's completion criteria."""

import json
import re
import runpy
from pathlib import Path
from typing import Any

from typer.testing import CliRunner

from agenticlens.cli.main import app

EXAMPLE = Path(__file__).resolve().parents[1] / "examples" / "modelfit"
#: Fields that legitimately differ between runs: wall-clock times, and the
#: experiment report's hash (it embeds its own creation time).
MEASURED = {"created_at", "sha256"}


def _normalize(value: Any) -> Any:
    if isinstance(value, dict):
        return {k: _normalize(v) for k, v in value.items() if k not in MEASURED}
    if isinstance(value, list):
        return [_normalize(item) for item in value]
    if isinstance(value, float):
        return round(value, 9)
    return value


def _load(path: Path) -> Any:
    return _normalize(json.loads(path.read_text("utf-8")))


def _experiment_outcomes(path: Path) -> Any:
    # agentic-evals owns the per-trial report format; compare outcomes, not layout.
    report = json.loads(path.read_text("utf-8"))
    return [
        (
            variant["variant_id"],
            [
                [(case["case_id"], case["passed"]) for case in trial["report"]["cases"]]
                for trial in variant["trials"]
            ],
        )
        for variant in report["variants"]
    ]


def _markdown(path: Path) -> str:
    return re.sub(r"sha256 `[0-9a-f]+`", "sha256 `…`", path.read_text("utf-8"))


def test_recorded_trials_are_reproducible(tmp_path: Path, monkeypatch) -> None:
    module = runpy.run_path(str(EXAMPLE / "record_trials.py"))
    monkeypatch.setitem(module["main"].__globals__, "HERE", tmp_path)
    module["main"]()
    for recorded in sorted((EXAMPLE / "recorded").iterdir()):
        produced = tmp_path / "recorded" / recorded.name
        assert produced.read_text("utf-8") == recorded.read_text("utf-8"), recorded.name


def test_modelfit_demo_reproduces_artifacts(tmp_path: Path) -> None:
    module = runpy.run_path(str(EXAMPLE.parent / "modelfit_demo.py"))
    result = module["main"](tmp_path)

    assert result["unfit"] == []
    saved = EXAMPLE / "artifacts"
    assert _experiment_outcomes(tmp_path / "experiment.json") == _experiment_outcomes(
        saved / "experiment.json"
    )
    assert _load(tmp_path / "modelfit.json") == _load(saved / "modelfit.json")
    assert _markdown(tmp_path / "modelfit.md") == _markdown(saved / "modelfit.md")
    assert (tmp_path / "model-matrix.csv").read_text("utf-8") == (
        saved / "model-matrix.csv"
    ).read_text("utf-8")


def test_committed_recommendations_meet_the_completion_criteria() -> None:
    report = json.loads((EXAMPLE / "artifacts" / "modelfit.json").read_text("utf-8"))
    by_id = {result["category"]["id"]: result for result in report["categories"]}

    # Recommendations are generated by task category.
    assert set(by_id) == {"all", "policy", "orders", "account", "safety"}
    assert all(r["recommendation"]["status"] == "recommended" for r in by_id.values())

    # Hard constraints are enforced: account data stays on-prem.
    account = by_id["account"]
    assert account["recommendation"]["variant_id"] == "oss-local"
    for candidate in account["candidates"]:
        if candidate["deployment"] != "on_prem":
            assert not candidate["feasible"]
            assert "allowed_deployments" in [v["constraint"] for v in candidate["violations"]]

    # Savings estimates are tied to experiment evidence.
    for result in by_id.values():
        savings = result["recommendation"]["savings"]
        assert savings["available"] and savings["source_indexes"] == [0]
        assert savings["reference_variant_id"] == "frontier-a"
        assert savings["recommended_attempts"] > 0 and savings["case_ids"]
    assert report["sources"][0]["experiment_name"] == "support-model-selection"

    # Quality risks and alternatives are reported.
    orders = by_id["orders"]["recommendation"]
    assert orders["variant_id"] == "small-a"
    assert "safety_failures" in [risk["kind"] for risk in orders["quality_risks"]]
    assert orders["fallback"]["variant_id"] == "mid-b"
    assert by_id["policy"]["recommendation"]["alternatives"]


def test_cli_reproduces_the_committed_report(tmp_path: Path) -> None:
    save = tmp_path / "modelfit.json"
    result = CliRunner().invoke(
        app,
        [
            "modelfit", "recommend", str(EXAMPLE / "artifacts" / "experiment.json"),
            "--config", str(EXAMPLE / "modelfit.yaml"),
            "--manifest", str(EXAMPLE / "support-experiment.yaml"),
            "--save", str(save), "--fail-on-unfit",
        ],
    )  # fmt: skip
    assert result.exit_code == 0, result.output
    assert _load(save) == _load(EXAMPLE / "artifacts" / "modelfit.json")
